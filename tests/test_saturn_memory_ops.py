"""Operational hardening for the Saturn memory bridge.

Covers the behaviours that make the store safe to run unattended:

* a local auth token is minted, persisted and actually enforced;
* ``/status`` pairs the revision with counts, mode and the last error;
* a drift report can prove the hybrid mirror did not silently diverge;
* reads retry a transient transport failure while mutations do not;
* one store cannot be claimed by two spawning processes;
* a strict write that fails during an outage is queued and replayed.
"""

from __future__ import annotations

import http.client
import shutil
import socket
import time
from pathlib import Path

import pytest

import memory.universal_bridge as ub

NODE_BINARY = shutil.which("node") or shutil.which("node.exe")
requires_node = pytest.mark.skipif(NODE_BINARY is None, reason="node is required")


def _free_port() -> int:
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return int(sock.getsockname()[1])


def _configure(monkeypatch, tmp_path: Path, namespace: str = "saturn-test"):
    port = _free_port()
    store = Path(tmp_path) / "store.jsonl"
    token_file = Path(tmp_path) / "sidecar.token"
    monkeypatch.setenv("SATURN_MEMORY_FILE", str(store))
    monkeypatch.setenv("SATURN_MEMORY_PORT", str(port))
    monkeypatch.setenv("SATURN_MEMORY_HOST", "127.0.0.1")
    monkeypatch.setenv("SATURN_MEMORY_URL", f"http://127.0.0.1:{port}")
    monkeypatch.setenv("SATURN_MEMORY_NAMESPACE", namespace)
    monkeypatch.setenv("SATURN_MEMORY_EMBED", "off")
    monkeypatch.setenv("SATURN_MEMORY_AUTOSTART", "1")
    monkeypatch.setenv("SATURN_MEMORY_ENABLED", "1")
    monkeypatch.setenv("SATURN_MEMORY_OUTBOX", "1")
    monkeypatch.setenv("SATURN_MEMORY_TOKEN_FILE", str(token_file))
    monkeypatch.setenv("SATURN_MEMORY_WRITE_TIMEOUT", "6")
    monkeypatch.setenv("SATURN_MEMORY_RECALL_TIMEOUT", "3")
    # Prove the growth control is forwarded to the engine, not just accepted.
    monkeypatch.setenv("SATURN_MEMORY_COMPACT_BYTES", "4096")
    # The token must be generated by the bridge, not supplied by the caller.
    monkeypatch.delenv("SATURN_MEMORY_KEY", raising=False)
    monkeypatch.delenv("SATURN_MEMORY_KEY", raising=False)
    return port, store, token_file


def _bridge_for(monkeypatch, tmp_path: Path):
    port, store, token_file = _configure(monkeypatch, tmp_path)
    bridge = ub.UniversalBridge()
    assert bridge.available(autostart=True), bridge._last_error
    return bridge, port, store, token_file


# ── Authentication ───────────────────────────────────────────────────────────

def test_token_is_persisted_and_stable(monkeypatch, tmp_path):
    token_file = Path(tmp_path) / "token"
    monkeypatch.setenv("SATURN_MEMORY_TOKEN_FILE", str(token_file))
    first = ub._read_or_create_token()
    second = ub._read_or_create_token()
    assert first and first == second
    assert token_file.read_text(encoding="utf-8").strip() == first


@requires_node
def test_auto_token_authenticates_owned_sidecar(monkeypatch, tmp_path):
    bridge, port, _store, token_file = _bridge_for(monkeypatch, tmp_path)
    try:
        assert bridge.api_key
        assert token_file.exists()
        assert token_file.read_text(encoding="utf-8").strip() == bridge.api_key

        report = bridge.health_report()
        assert report["ok"] is True, report
        assert report["owned"] is True
        assert report["namespace"] == "saturn-test"

        # The token is enforced: an unauthenticated caller is refused.
        connection = http.client.HTTPConnection("127.0.0.1", port, timeout=3)
        try:
            connection.request("GET", "/status")
            response = connection.getresponse()
            assert response.status == 401
            response.read()
        finally:
            connection.close()
    finally:
        bridge.stop()


@requires_node
def test_second_bridge_adopts_without_owning(monkeypatch, tmp_path):
    first, _port, _store, token_file = _bridge_for(monkeypatch, tmp_path)
    try:
        first_pid = first.status()["pid"]

        # A fresh instance in the same environment has no key of its own yet.
        second = ub.UniversalBridge()
        assert second.available(autostart=True), second._last_error
        assert second.api_key == token_file.read_text(encoding="utf-8").strip()
        assert second._owns_process is False
        assert second._process is None
        assert second.status()["pid"] == first_pid

        # An adopter must never stop the owner's sidecar.
        second.stop()
        assert first.status()["ok"] is True
        assert first.status()["pid"] == first_pid
    finally:
        first.stop()


# ── Status ───────────────────────────────────────────────────────────────────

@requires_node
def test_status_reports_revision_and_counts(monkeypatch, tmp_path):
    bridge, _port, store, _token = _bridge_for(monkeypatch, tmp_path)
    try:
        before = bridge.status()
        assert before["ok"] is True
        assert before["count"] == 0
        # Revision stays a (process epoch, counter) pair; no extra segments.
        assert before["revision"].count(":") == 1

        result = bridge.remember_entry({"text": "The user's name is Ada", "kind": "fact"})
        assert result.get("id"), result

        after = bridge.status()
        assert after["count"] == 1
        assert after["revision"] != before["revision"]
        assert after["compactBytes"] == 4096
        assert Path(after["file"]).resolve() == store.resolve()

        report = bridge.health_report()
        assert report["count"] == 1
        assert report["mode"]
        assert report["pending_writes"] == 0
    finally:
        bridge.stop()


# ── Drift ────────────────────────────────────────────────────────────────────

@requires_node
def test_drift_report_detects_divergence(monkeypatch, tmp_path):
    bridge, _port, _store, _token = _bridge_for(monkeypatch, tmp_path)
    try:
        profile = {"identity": {"name": {"value": "Ada", "updated": "2026-01-01"}}}
        bridge.write_profile(profile, autostart=True)

        clean = bridge.drift_report(profile)
        assert clean["ok"] is True, clean

        changed = bridge.drift_report(
            {"identity": {"name": {"value": "Bob", "updated": "2026-01-01"}}}
        )
        assert changed["counts"]["changed"] == 1, changed

        moved = bridge.drift_report(
            {"identity": {"city": {"value": "Delhi", "updated": "2026-01-01"}}}
        )
        assert moved["counts"]["missing"] == 1, moved
        assert moved["counts"]["extra"] == 1, moved
    finally:
        bridge.stop()


# ── Retry policy ─────────────────────────────────────────────────────────────

def test_get_retries_transport_failures_but_post_does_not(monkeypatch):
    bridge = ub.UniversalBridge()
    monkeypatch.setattr(ub.time, "sleep", lambda _seconds: None)
    calls = {"n": 0}

    def flaky_once(method, path, payload=None, timeout=10.0):
        calls["n"] += 1
        if calls["n"] <= 2:
            raise ConnectionResetError("transient reset")
        return {"ok": True}

    monkeypatch.setattr(bridge, "_request_once", flaky_once)
    assert bridge._request("GET", "/health") == {"ok": True}
    assert calls["n"] == 3

    calls["n"] = 0
    with pytest.raises(ConnectionResetError):
        bridge._request("POST", "/remember", {"text": "x"})
    assert calls["n"] == 1


# ── Single owner per store ───────────────────────────────────────────────────

def test_spawn_lock_allows_only_one_owner(monkeypatch, tmp_path):
    monkeypatch.setenv("SATURN_MEMORY_FILE", str(Path(tmp_path) / "store.jsonl"))
    first = ub.UniversalBridge()
    second = ub.UniversalBridge()
    try:
        assert first._claim_spawn() is True
        assert second._claim_spawn() is False
        first._release_spawn_lock()
        assert second._claim_spawn() is True
    finally:
        second._release_spawn_lock()


# ── Outbox ───────────────────────────────────────────────────────────────────

@requires_node
def test_outbox_replays_after_a_transient_outage(monkeypatch, tmp_path):
    bridge, _port, _store, _token = _bridge_for(monkeypatch, tmp_path)
    real_sync = bridge._sync
    try:
        def down(*_args, **_kwargs):
            raise ub.SaturnUnavailable("store is away")

        monkeypatch.setattr(bridge, "_sync", down)
        profile = {"identity": {"name": {"value": "Ada", "updated": "2026-01-01"}}}
        with pytest.raises(ub.SaturnUnavailable):
            bridge.write_profile(profile, autostart=True)
        assert bridge.pending_writes() == 1

        # The outage passes: the live write replays the queued intent first.
        monkeypatch.setattr(bridge, "_sync", real_sync)
        bridge.write_profile(profile, autostart=True)
        assert bridge.pending_writes() == 0
        assert bridge.status()["count"] >= 1
    finally:
        bridge.stop()
